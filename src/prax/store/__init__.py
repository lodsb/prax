"""prax.store — the only module that touches SQLite.

Everything else (the door, the MCP proxy, the importers, the one-off
scripts) calls these functions: ingest in two steps (``register``,
``index_text``), search, the graph, pages, jobs. It was one file until it
passed four thousand lines; it is a package now, one module per concern,
and every public name a caller outside the store uses is re-exported
here as ``store.<name>``. A part's private helpers (``_serialized``,
``rows_in``, ``first_fresh_id``) stay in the package that holds them
(``store.base``), out of this surface since 7175aa8.

Concurrency: the door runs sync handlers on worker threads, so connections
are created with ``check_same_thread=False``, reads take a connection per
thread (``thread_connection``) and every write is serialized behind one
process-wide re-entrant lock (invariant 4).

| module | what lives there |
|---|---|
| ``base`` | connection, lock, archive, index files, a domain's documents |
| ``documents`` | ingest, read, meta, domains, genres, readings, retiring |
| ``retrieval`` | query expansion, FTS, vectors, fusion, rerank |
| ``graph`` | entities, edges, names, regions, traversal, the review queue |
| ``pages`` | the notes that are documents too |
| ``jobs`` | what runs and what ran |
| ``summary`` | what the store holds, counted |
| ``repair`` | the damage that recurs: `health` finds it, `heal` mends it |
| ``maintain`` | the derived tables rebuilt, without a model |
| ``backup`` | a copy of the store somewhere else, incrementally |
"""

